"""Generates taxonomy/springer-<discipline>.yml classification schemes from Springer Nature's
subject codes (the Product Market Codes behind SpringerLink's disciplines and subdisciplines).

Usage: python3 scripts/springer.py [ARCHIVE_URL_OR_PATH]

One file per discipline. Springer nests everything in a discipline under a "<Discipline>,
general" concept; that concept is kept as an entry of its own and its children become the top
level, so a key is a subject group and, below it, a subdiscipline, each step in PascalCase:

    SoftwareEngineeringProgrammingAndOperatingSystems/ProgrammingLanguagesCompilersInterpreters

The data is published by Springer Nature SciGraph under CC BY-NC 4.0.
"""

import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

# "Schema: Product Market Codes" on figshare, https://doi.org/10.6084/m9.figshare.7376447
DEFAULT_SOURCE = "https://ndownloader.figshare.com/files/39015875"
OUT_DIR = Path(__file__).resolve().parent.parent / "taxonomy"
# Disciplines that are not research fields: "multidisciplinary" and "Popular Science".
SKIPPED = {"A", "Q"}


def load(source: str) -> bytes:
    if re.match(r"https?://", source):
        request = urllib.request.Request(source, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request) as response:
            return response.read()
    return Path(source).read_bytes()


def pascal(label: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", re.sub(r"\(.*?\)", "", label))
    return "".join(w[:1].upper() + w[1:] for w in words)


def slug(label: str) -> str:
    return "-".join(re.findall(r"[a-z0-9]+", label.lower()))


def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    archive = tarfile.open(fileobj=io.BytesIO(load(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SOURCE)))
    nodes = {}
    for member in archive.getmembers():
        if not member.name.endswith(".jsonl"):
            continue
        for line in archive.extractfile(member):
            d = json.loads(line)
            if "skos:prefLabel" not in d:
                continue  # the concept scheme itself, not a concept
            code = d["id"].rsplit("/", 1)[-1]
            nodes[code] = {
                "label": next(l["@value"] for l in d["skos:prefLabel"] if l["@language"] == "en"),
                "broader": [b["id"].rsplit("/", 1)[-1] for b in d.get("skos:broader", [])],
                "top": "skos:topConceptOf" in d,
            }
    children = {}
    for code in sorted(nodes):
        for parent in nodes[code]["broader"][:1]:
            children.setdefault(parent, []).append(code)

    OUT_DIR.mkdir(exist_ok=True)
    for top in sorted(c for c, n in nodes.items() if n["top"] and c not in SKIPPED):
        discipline = nodes[top]["label"]
        entries = {}

        def add(code: str, prefix: str) -> None:
            path = prefix + pascal(nodes[code]["label"])
            assert path not in entries, f"two entries at {path}"
            entries[path] = nodes[code]["label"]
            for child in children.get(code, []):
                add(child, path + "/")

        for general in children.get(top, []):
            entries[pascal(nodes[general]["label"])] = nodes[general]["label"]
            for child in children.get(general, []):
                add(child, "")

        out = OUT_DIR / f"springer-{slug(discipline)}.yml"
        lines = [
            f"# Springer Nature subjects of the {discipline} discipline (Product Market Codes, {top}).",
            "# Springer Nature SciGraph, CC BY-NC 4.0. Generated by scripts/springer.py; do not edit by hand.",
            "",
        ]
        lines += [f"{path}: {quote(label)}" for path, label in entries.items()]
        out.write_text("\n".join(lines) + "\n")
        print(f"{len(entries):4} subjects written to {out.relative_to(OUT_DIR.parent)}")


if __name__ == "__main__":
    main()
