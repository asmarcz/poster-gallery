"""Generates taxonomy/biorxiv.yml, taxonomy/medrxiv.yml and taxonomy/chemrxiv.yml, the subject
areas of the bioRxiv, medRxiv and ChemRxiv preprint servers.

Usage: python3 scripts/rxiv.py

bioRxiv and medRxiv list their subject areas as /collection/<slug> links on their home pages.
ChemRxiv's categories (and their subcategories) are only served by an API behind a Cloudflare
check that scripts can't pass, so its 17 top-level subjects are listed here, as given in
ChemRxiv's repository record (https://doapr.coar-repositories.org/repositories/chemrxiv/).
Each key is the subject's name in PascalCase.
"""

import html
import re
import urllib.request
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent.parent / "taxonomy"
SCRAPED = {
    "biorxiv": ("bioRxiv", "https://www.biorxiv.org/"),
    "medrxiv": ("medRxiv", "https://www.medrxiv.org/"),
}
CHEMRXIV = [
    "Agriculture and Food Chemistry",
    "Analytical Chemistry",
    "Biological and Medicinal Chemistry",
    "Catalysis",
    "Chemical Education",
    "Chemical Engineering and Industrial Chemistry",
    "Earth, Space, and Environmental Chemistry",
    "Energy",
    "Inorganic Chemistry",
    "Materials Chemistry",
    "Materials Science",
    "Nanoscience",
    "Organic Chemistry",
    "Organometallic Chemistry",
    "Physical Chemistry",
    "Polymer Science",
    "Theoretical and Computational Chemistry",
]


def pascal(label: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", re.sub(r"\(.*?\)", "", label))
    return "".join(w[:1].upper() + w[1:] for w in words)


def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(name: str, server: str, source: str, subjects: list[str]) -> None:
    out = OUT_DIR / f"{name}.yml"
    keys = [pascal(s) for s in subjects]
    assert len(set(keys)) == len(keys), f"two {server} subjects share a key"
    lines = [
        f"# {server} subject areas, from {source}.",
        "# Generated by scripts/rxiv.py; do not edit by hand.",
        "",
    ]
    lines += [f"{key}: {quote(subject)}" for key, subject in zip(keys, subjects)]
    OUT_DIR.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(subjects):3} subjects written to {out.relative_to(OUT_DIR.parent)}")


def main() -> None:
    for name, (server, page_url) in SCRAPED.items():
        request = urllib.request.Request(page_url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request) as response:
            page = response.read().decode("utf-8")
        subjects = sorted({html.unescape(s).strip() for s in re.findall(r'href="/collection/[^"]+"[^>]*>([^<]+)<', page)})
        assert subjects, f"no subject areas found on {page_url}; the page layout may have changed"
        write(name, server, page_url, subjects)
    write("chemrxiv", "ChemRxiv", "its COAR repository record", CHEMRXIV)


if __name__ == "__main__":
    main()
