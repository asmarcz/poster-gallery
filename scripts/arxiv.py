"""Generates taxonomy/arxiv-<group>.yml classification schemes from arXiv's category taxonomy.

Usage: python3 scripts/arxiv.py [GROUP ...]     (default: every group)

GROUP is an arXiv group: cs, econ, eess, math, physics, q-bio, q-fin or stat. Each category
becomes one entry keyed by its arXiv id. Categories inside an archive of their own (physics
has astro-ph, cond-mat, …) are nested under it:

    cs.PL
    astro-ph/astro-ph.CO
"""

import html
import re
import sys
import urllib.request
from pathlib import Path

SOURCE = "https://arxiv.org/category_taxonomy"
OUT_DIR = Path(__file__).resolve().parent.parent / "taxonomy"


def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request) as response:
        page = response.read().decode("utf-8")

    # The page is one section per group, each opened by <h2 … id="accordion-head-grp_<group>">.
    sections = re.split(r'<h2 class="accordion-head" id="accordion-head-grp_', page)[1:]
    by_group = {s.split('"', 1)[0]: s for s in sections}
    groups = sys.argv[1:] or list(by_group)

    for group in groups:
        if group not in by_group:
            sys.exit(f"unknown arXiv group {group!r}; known: {', '.join(by_group)}")
        section = by_group[group]
        archives = {
            code: html.unescape(name)
            for name, code in re.findall(r"<h3>([^<]+)<br><span>\(([^)]+)\)</span></h3>", section)
        }
        entries = {}
        for code, name in re.findall(r"<h4>([^<\s]+) <span>\(([^)]+)\)</span></h4>", section):
            name = html.unescape(name)
            archive = code.split(".")[0]
            if "." in code and archive != group:
                entries.setdefault(archive, f"{archives.get(archive, archive)} ({archive})")
                entries[f"{archive}/{code}"] = f"{name} ({code})"
            else:
                entries[code] = f"{name} ({code})"

        out = OUT_DIR / f"arxiv-{group}.yml"
        lines = [
            f"# arXiv categories of the {group} group, https://arxiv.org/category_taxonomy.",
            "# Generated by scripts/arxiv.py; do not edit by hand.",
            "",
        ]
        lines += [f"{key}: {quote(label)}" for key, label in entries.items()]
        OUT_DIR.mkdir(exist_ok=True)
        out.write_text("\n".join(lines) + "\n")
        print(f"{len(entries)} categories written to {out.relative_to(OUT_DIR.parent)}")


if __name__ == "__main__":
    main()
