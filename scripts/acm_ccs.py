"""Generates taxonomy/acm-ccs.yml, a classification scheme, from the ACM Computing Classification System.

Usage: python3 scripts/acm_ccs.py [CCS_XML_URL_OR_PATH]

Every concept of the CCS 2012 tree becomes one entry. Its key is its path in the tree, each
step in PascalCase:

    SoftwareAndItsEngineering/SoftwareNotationsAndTools/Compilers/JustInTimeCompilers

ACM repeats some concepts in several places (e.g. "Parallel programming languages" under both
"Software and its engineering" and "Computing methodologies"); each place gets its own id.
"""

import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_SOURCE = "https://dl.acm.org/pb-assets/dl_ccs/acm_ccs2012-1626988337597.xml"
OUT = Path(__file__).resolve().parent.parent / "taxonomy" / "acm-ccs.yml"
NS = {
    "rdf": "http://www.w3.org/1999/02/22-rdf-syntax-ns#",
    "skos": "http://www.w3.org/2004/02/skos/core#",
}
RDF = "{%s}" % NS["rdf"]
# ACM's own order of the top-level classes; the file lists them in another order.
CLASS_ORDER = [
    "General and reference", "Hardware", "Computer systems organization", "Networks",
    "Software and its engineering", "Theory of computation", "Mathematics of computing",
    "Information systems", "Security and privacy", "Human-centered computing",
    "Computing methodologies", "Applied computing", "Social and professional topics",
]


def load(source: str) -> bytes:
    if re.match(r"https?://", source):
        request = urllib.request.Request(source, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(request) as response:
            return response.read()
    return Path(source).read_bytes()


def pascal(label: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", re.sub(r"\(.*?\)", "", label))
    return "".join(w[:1].upper() + w[1:] for w in words)


def quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    root = ET.fromstring(load(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SOURCE))
    labels, narrower = {}, {}
    for c in root.findall("skos:Concept", NS):
        cid = c.get(RDF + "about")
        labels[cid] = c.find("skos:prefLabel", NS).text.strip()
        narrower[cid] = [n.get(RDF + "resource") for n in c.findall("skos:narrower", NS)]

    scheme = root.find("skos:ConceptScheme", NS)
    by_label = {labels[t.get(RDF + "resource")]: t.get(RDF + "resource") for t in scheme.findall("skos:hasTopConcept", NS)}

    # Depth-first in ACM order, so every concept follows its parent.
    entries = []
    stack = [(by_label[name], "") for name in reversed(CLASS_ORDER)]
    while stack:
        cid, prefix = stack.pop()
        path = f"{prefix}{pascal(labels[cid])}"
        entries.append((path, labels[cid]))
        stack.extend((child, path + "/") for child in reversed(narrower[cid]))

    paths = [p for p, _ in entries]
    duplicates = sorted({p for p in paths if paths.count(p) > 1})
    assert not duplicates, f"siblings with the same name: {duplicates}"

    lines = [
        "# The ACM Computing Classification System (2012), https://dl.acm.org/ccs.",
        "# Generated by scripts/acm_ccs.py; do not edit by hand.",
        "# Each key is the concept's path in the ACM tree.",
        "",
    ]
    lines += [f"{path}: {quote(label)}" for path, label in entries]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(entries)} concepts written to {OUT.relative_to(OUT.parent.parent)}")


if __name__ == "__main__":
    main()
